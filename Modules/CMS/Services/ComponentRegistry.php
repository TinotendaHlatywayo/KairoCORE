    public static function component(string $type): ?array
    {
        return self::catalog()[$type] ?? null;
    }

    public static function variantsFor(string $type): array
    {
        $def = self::component($type);

        return self::variants()[$type] ?? [
            ['variant_key' => $def['default_variant'] ?? 'default', 'name' => $def['name'] ?? ucwords(str_replace('_', ' ', $type)), 'template_origin' => null, 'config' => []],
        ];
    }

    public static function defaultVariant(string $type): string
    {
        return self::component($type)['default_variant'] ?? 'default';
    }

    public static function hasVariant(string $type, ?string $variant): bool
    {
        if ($variant === null || $variant === '') {
            return true;
        }

        return collect(self::variantsFor($type))->contains('variant_key', $variant);
    }

    public static function safeVariant(string $type, ?string $variant): string
    {
        return self::hasVariant($type, $variant) ? ($variant ?: self::defaultVariant($type)) : self::defaultVariant($type);
    }

    /** Merge registry defaults (defaults + variant-aware overrides) into a block. */
    public static function normalizeBlock(array $block): array
    {
        $type = $block['type'] ?? '';
        $def = self::component($type);
        if ($def === null) {
            return $block;
        }

        $variant = self::safeVariant($type, $block['variant'] ?? null);
        $block['variant'] = $variant;

        $defaults = [];
        foreach ($def['props'] as $key => $field) {
            if (array_key_exists('default', $field)) {
                $defaults[$key] = $field['default'];
            }
        }

        // Variant-specific config overrides (from variant.config) applied last.
        foreach (self::variantsFor($type) as $vc) {
            if ($vc['variant_key'] === $variant && ! empty($vc['config'])) {
                $defaults = array_replace($defaults, $vc['config']);
            }
        }

        // Merge without clobbering styles/ids or stored props.
        foreach ($defaults as $key => $value) {
            if (! array_key_exists($key, $block)) {
                $block[$key] = $value;
            }
        }

        return $block;
    }

    public static function categories(): array
    {
        return collect(self::catalog())->map(fn ($c) => $c['category'])->unique()->values()->all();
    }

    /** Blocks available for the cross-template "add block" picker, grouped. */
    public static function pickerOptions(?string $category = null): array
    {
        $catalog = collect(self::catalog());
        if ($category) {
            $catalog = $catalog->where('category', $category);
        }

        return $catalog
            ->map(fn ($def, $type) => [
                'type' => $type,
                'name' => $def['name'],
                'spec' => $def['spec'] ?? self::specKey($type),
                'category' => $def['category'],
                'description' => $def['description'] ?? '',
                'variants' => collect(self::variantsFor($type))->pluck('variant_key')->values()->all(),
            ])
            ->values()
            ->all();
    }
