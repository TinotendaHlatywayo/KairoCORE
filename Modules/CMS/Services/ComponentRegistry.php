    /** @var array<string, array{name: string, category: string, ...}> */
    private static ?array $catalog = null;

    /** @var array<string, array<string, array>> */
    private static ?array $variants = null;

    public static function placeholderImages(): array
    {
        return self::PLACEHOLDER_IMAGES;
    }

    public static function placeholderUrl(string $key, string $fallback = 'campus-exterior'): string
    {
        $path = self::PLACEHOLDER_IMAGES[$key] ?? self::PLACEHOLDER_IMAGES[$fallback] ?? self::PLACEHOLDER_IMAGES['campus-exterior'];

        return asset($path);
    }

    /** True when an image URL points at one of our shipped placeholders. */
    public static function isPlaceholder(?string $url): bool
    {
        if ($url === null || $url === '') {
            return false;
        }
        foreach (self::PLACEHOLDER_IMAGES as $path) {
            if (str_contains($url, $path)) {
                return true;
            }
        }

        return false;
    }

