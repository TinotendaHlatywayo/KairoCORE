    /**
     * The procurement template carries no prefilled example row: request numbers
     * and requesters are generated by the system, and an example data row would
     * otherwise turn into a rejected/re-imported record.
     */
    public static function templateCsv(): string
    {
        $out = fopen('php://temp', 'r+');
        fwrite($out, "\xEF\xBB\xBF");
        fputcsv($out, static::exportHeaders());

        $examples = [
            ['Academics', 'draft', 'medium', 'A4 Paper; Printer Toner', '10; 2', '5.50; 85.00', 'Term 1 stationery requisition', 'Deliver to administration block'],
            ['Administration', 'pending_approval', 'high', 'Whiteboard Markers; Erasers', '5; 5', '2.00; 1.50', 'Staff room supplies', 'Urgent for meetings'],
            ['Science', 'draft', 'low', 'Test Tubes; Beakers; Bunsen Burner', '20; 10; 2', '1.20; 3.50; 25.00', 'Laboratory practicals', 'Handle with care'],
            ['Sports', 'approved', 'medium', 'Football; Whistles; Cones', '3; 4; 20', '25.00; 3.00; 0.50', 'Inter-house sports equipment', 'Store in PE equipment room'],
            ['Maintenance', 'draft', 'emergency', 'LED Bulbs; Door Hinges; Padlocks', '12; 6; 4', '4.50; 6.00; 12.00', 'Campus security and lighting repairs', 'Immediate replacement required'],
        ];

        foreach ($examples as $row) {
            fputcsv($out, $row);
        }

        rewind($out);
        $csv = stream_get_contents($out);
        fclose($out);

        return $csv;
    }

